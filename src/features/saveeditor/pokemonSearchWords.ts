export function searchSourceLabel(
  key: keyof typeof source,
  lang: "zh" | "en" | "ja",
) {
  const ja: Partial<Record<keyof typeof source, string>> = {
    "EntitySearchSetup.B_Add": "追加",
    "EntitySearchSetup.B_Next": "次へ",
    "EntitySearchSetup.B_Previous": "前へ",
    "EntitySearchSetup.B_Reset": "条件をリセット",
    "EntitySearchSetup.B_Search": "検索",
  };
  return lang === "ja" ? (ja[key] ?? source[key][lang]) : source[key][lang];
}
